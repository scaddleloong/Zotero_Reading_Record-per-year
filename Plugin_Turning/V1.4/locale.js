// ---- Locale lookup ----
function _loc(key) {
    var langMap = _STRINGS[_LANG];
    if (!langMap) langMap = _STRINGS["en"];
    var val = langMap[key];
    if (val === undefined) val = _STRINGS["en"][key];
    if (val === undefined) val = key;
    // substitute {0}, {1}, ...
    if (arguments.length > 1) {
        for (var i = 1; i < arguments.length; i++) {
            val = String(val).replace(new RegExp("\\{" + (i - 1) + "\\}", "g"), String(arguments[i]));
        }
    }
    return val;
}
