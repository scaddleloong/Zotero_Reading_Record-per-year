// ---- Detect Zotero locale ----
var _LOCALE = "en-US";
try { _LOCALE = Zotero.locale || "en-US"; } catch (e) {}

// Map full locale to supported language code
function _mapLang(locale) {
    var lang = (locale || "").split("-")[0].toLowerCase();
    var supported = ["en","zh","es","fr","pt","ru","de","ja","ar","hi"];
    if (lang === "zh") return "zh-CN";
    if (supported.indexOf(lang) !== -1) return lang;
    return "en";
}
var _LANG = _mapLang(_LOCALE);

// ---- Intl-based month / weekday names (for ALL locales) ----
var _MONTHS = (function() {
    var a = [];
    for (var i = 0; i < 12; i++) {
        try { a.push(new Intl.DateTimeFormat(_LOCALE, {month: "short"}).format(new Date(2000, i, 1))); }
        catch (e) { a.push(["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"][i]); }
    }
    return a;
})();

var _WEEKDAYS = (function() {
    // Sun=0 … Sat=6; we want Mon..Sun order
    var a = [], map = [1,2,3,4,5,6,0];
    for (var i = 0; i < 7; i++) {
        try { a.push(new Intl.DateTimeFormat(_LOCALE, {weekday: "short"}).format(new Date(2021, 2, map[i]))); }
        catch (e) { a.push(["Mon","Tue","Wed","Thu","Fri","Sat","Sun"][i]); }
    }
    return a;
})();

